// README screenshot gallery (used by scripts/screenshots.mjs). Pure functions, tested in tests/ui/readme-gallery.test.ts.

/** README gallery: [image name, caption]. */
export const GALLERY = [
  ["settings-shortcuts", "Global shortcuts – change any of them"],
  ["prompts", "Prompt menu (Alt+J) – saved prompts for your next message"],
  ["indicator", "Voice message running – Gemini's own speech recognition"],
  ["overlay", "Screenshot & Ask (Alt+Shift+S) – select an area, it lands in your prompt"],
  ["settings-voice", "Voice settings"],
  ["toast", "Dictation (Alt+Shift+V) – the recognised text is in your clipboard"],
];

/** Builds the README gallery: <picture> elements that follow the reader's GitHub theme. */
export function galleryMarkdown(gallery = GALLERY) {
  const img = (name, caption) =>
    `<picture><source media="(prefers-color-scheme: dark)" srcset="images/screenshots/${name}-dark.png">` +
    `<img src="images/screenshots/${name}-light.png" alt="${caption}" width="100%"></picture>`;
  const rows = [];
  for (let i = 0; i < gallery.length; i += 2) {
    const cells = gallery.slice(i, i + 2)
      .map(([n, c]) => `<td width="50%" valign="top">${img(n, c)}<br><sub>${c}</sub></td>`)
      .join("");
    rows.push(`<tr>${cells}</tr>`);
  }
  return [
    `<p align="center">${img("hero", "Gemini Tray: the Gemini window with prompt menu and voice indicator")}</p>`,
    "",
    `<table>${rows.join("")}</table>`,
  ].join("\n");
}

export function replaceBetweenMarkers(text, block) {
  const start = "<!-- screenshots:start -->";
  const end = "<!-- screenshots:end -->";
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a < 0 || b < a) throw new Error(`README.md needs the markers ${start} … ${end}`);
  // Keep the file's line endings (a Windows checkout has CRLF).
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const inner = `<!-- Generated by scripts/screenshots.mjs – do not edit by hand. -->\n${block}`.replace(/\r?\n/g, eol);
  return `${text.slice(0, a + start.length)}${eol}${inner}${eol}${text.slice(b)}`;
}
