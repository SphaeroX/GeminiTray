import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
// @ts-expect-error – plain ESM script without type declarations
import { GALLERY, galleryMarkdown, replaceBetweenMarkers } from "../../scripts/readme-gallery.mjs";

const START = "<!-- screenshots:start -->";
const END = "<!-- screenshots:end -->";
const NOTE = "<!-- Generated by scripts/screenshots.mjs – do not edit by hand. -->";

describe("README screenshot gallery", () => {
  it("replaces only the text between the markers", () => {
    const text = `# Title\n${START}\nold\n${END}\n## Rest`;
    const next = replaceBetweenMarkers(text, "NEW");
    expect(next).toBe(`# Title\n${START}\n${NOTE}\nNEW\n${END}\n## Rest`);
  });

  it("is idempotent", () => {
    const text = `${START}\n${END}`;
    const once = replaceBetweenMarkers(text, galleryMarkdown());
    expect(replaceBetweenMarkers(once, galleryMarkdown())).toBe(once);
  });

  it("keeps CRLF line endings", () => {
    const next = replaceBetweenMarkers(`a\r\n${START}\r\n${END}\r\nb`, "x\ny");
    expect(next).toBe(`a\r\n${START}\r\n${NOTE}\r\nx\r\ny\r\n${END}\r\nb`);
  });

  it("fails loudly without markers", () => {
    expect(() => replaceBetweenMarkers("# no markers", "x")).toThrow(/markers/);
  });

  it("shows light and dark variants of every image", () => {
    const md = galleryMarkdown([["prompts", "Prompt menu"]]);
    expect(md).toContain('srcset="images/screenshots/prompts-dark.png"');
    expect(md).toContain('src="images/screenshots/prompts-light.png"');
    expect(md).toContain("<sub>Prompt menu</sub>");
  });

  it("matches the README checked into the repository", () => {
    const readme = readFileSync(resolve(import.meta.dirname, "../../README.md"), "utf8").replace(/\r\n/g, "\n");
    expect(readme).toContain(galleryMarkdown(GALLERY));
  });
});
